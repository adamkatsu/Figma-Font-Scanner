#!/usr/bin/env node
/**
 * Fetches Google Fonts family names (no API key) and writes a TypeScript module
 * for offline classification in the plugin UI.
 *
 * Source: https://fonts.google.com/metadata/fonts
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(__dirname, '../ui/src/data/googleFontFamilies.ts');
const URL = 'https://fonts.google.com/metadata/fonts';

const res = await fetch(URL);
if (!res.ok) {
  console.error(`Failed to fetch ${URL}: ${res.status} ${res.statusText}`);
  process.exit(1);
}

let text = await res.text();
// Google sometimes prefixes JSON with )]}'
if (text.startsWith(")]}'")) {
  text = text.replace(/^\)\]\}'\n?/, '');
}

const data = JSON.parse(text);
const list = data.familyMetadataList;
if (!Array.isArray(list) || list.length === 0) {
  console.error('Unexpected metadata shape: missing familyMetadataList');
  process.exit(1);
}

const families = [...new Set(list.map((f) => f.family).filter(Boolean))].sort((a, b) =>
  a.localeCompare(b)
);
const lower = families.map((f) => f.toLowerCase());

const generatedAt = new Date().toISOString().slice(0, 10);

const file = `/* eslint-disable */
// Auto-generated by scripts/fetch-google-fonts.mjs — do not edit by hand.
// Generated: ${generatedAt}
// Families: ${families.length}

export const GOOGLE_FONT_FAMILIES: readonly string[] = ${JSON.stringify(families, null, 2)};

/** Lowercase family names for O(1) lookup */
export const GOOGLE_FONT_FAMILY_SET: ReadonlySet<string> = new Set(
  ${JSON.stringify(lower)}
);
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, file, 'utf8');
console.log(`Wrote ${families.length} families to ${path.relative(process.cwd(), OUT)}`);
